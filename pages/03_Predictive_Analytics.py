"""Page 3: forecasts with explicit uncertainty and honesty labels."""
import sys, os
sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import streamlit as st

from config.settings import TICKERS, START_DATE, END_DATE
from src import data_collection as dc, visualization as viz
from src.forecasting import bootstrap_forecast, regime_up_probability

st.title("🔮 Predictive Analytics")
st.warning("Everything on this page is a **model estimate with wide uncertainty** — "
           "not a prediction of what markets will do. Method and limitations are stated for each output.")

@st.cache_data(ttl=3600, show_spinner="Fetching data and running models...")
def load(_tickers, start, end):
    prices = dc.fetch_prices(_tickers, start, end)
    return prices, dc.compute_returns(prices)

prices, returns = load(tuple(TICKERS), START_DATE, END_DATE)

st.subheader("1) Block-bootstrap portfolio forecast")
st.markdown("**What:** distribution of next-12-month portfolio returns, generated by resampling "
            "blocks of the portfolio's own daily return history (preserves fat tails). "
            "**Method:** stationary block bootstrap, 21-day blocks, 1,000 paths. "
            "**Limitation:** assumes the future resembles the resampled history; regime shifts are not modelled.")
col1, col2 = st.columns(2)
strategy = col1.selectbox("Portfolio to forecast",
                          ["1/N equal weight", "MVO 20% cap (proxy: equal weight of 5 names)"])
horizon = col2.slider("Horizon (trading days)", 21, 504, 252, 21)
w = {t: 1 / len(TICKERS) for t in TICKERS}
fc = bootstrap_forecast(returns, w, horizon_days=int(horizon))
st.plotly_chart(viz.monte_carlo_fan(fc, f"{horizon} trading days"), width="stretch")
st.markdown(f"Mean: **{fc['mean']:.1%}** · Probability of loss: **{fc['prob_loss']:.1%}** · "
            f"90% interval: [{fc[5]:.1%}, {fc[95]:.1%}]")

st.subheader("2) Regime probability (machine learning)")
st.markdown("**What:** a random-forest classifier estimates the probability that a ticker's next "
            "quarter return is positive, using momentum, volatility and drawdown features. "
            "**Validation:** walk-forward on the most recent 30% of the sample (no look-ahead). "
            "**Limitation:** near-coin-flip accuracy is common in equity prediction — treat as a weak signal.")
ticker = st.selectbox("Ticker", TICKERS)
ml = regime_up_probability(returns, ticker)
if ml is None:
    st.info("Model unavailable for this input (insufficient data). Nothing is fabricated.")
else:
    c1, c2 = st.columns(2)
    c1.metric(f"P(next 63d up) — {ticker}", f"{ml['up_probability']:.1%}")
    c2.metric("Walk-forward accuracy", f"{ml['walkforward_accuracy']:.1%}")
    st.caption(ml["note"])
